import io

BASE = "aa-sl/01-number-and-algebra/"
COUNT = 0
_cur = {"path": None, "s": None}


def open_file(path):
    _cur["path"] = path
    _cur["s"] = io.open(path, encoding="utf-8").read()


def rep(o, nw):
    global COUNT
    s = _cur["s"]
    assert o in s, "NOT FOUND in %s: %s" % (_cur["path"], o[:70])
    assert s.count(o) == 1, "MULTIPLE(%d) in %s: %s" % (
        s.count(o), _cur["path"], o[:70])
    _cur["s"] = s.replace(o, nw, 1)
    COUNT += 1


def save():
    io.open(_cur["path"], "w", encoding="utf-8").write(_cur["s"])
    print("  saved", _cur["path"])


